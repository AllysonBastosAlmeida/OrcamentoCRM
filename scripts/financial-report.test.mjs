import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import ExcelJS from 'exceljs';
import XLSX from 'xlsx';
import evidence from '../src/data/financialEvidence.json' with {type:'json'};
import { extractFinancialQuotes, extractLegacyQuote, recoverFinancialDetails, linkFinancialInvoices, attachFinancialSummaries, sourceDate, financialAnalysis } from '../src/utils/financialExtraction.js';
import { buildFinancialWorkbook } from '../src/utils/financialReport.js';
const hash=(p)=>createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const sourcePath=process.argv[2] || 'tmp/orcamento-fonte-2026-10-16.xlsx';
const before=hash(sourcePath);
const quotes=extractFinancialQuotes(XLSX.readFile(sourcePath),'SharePoint: Orçamento Web.xlsx obtido em 16/10/2026');
const originals=evidence.originals.map(o=>extractLegacyQuote(XLSX.readFile(`tmp/financial-original-${o.key}.xlsx`),o.title));
for(const d of evidence.invoices)assert.equal(hash(`tmp/financial-nf-${d.index}.pdf`),d.sha256,'PDF fiscal alterado');
assert.equal(hash('tmp/financial-po107.pdf'),evidence.summaries[0].sha256);
const extracted=attachFinancialSummaries(linkFinancialInvoices(recoverFinancialDetails(quotes,originals),evidence.invoices),evidence.summaries);
const inputJSON=JSON.stringify(extracted);
const options={start:'2026-01-01',end:'2026-12-31',cutoff:'2026-10-16',client:'Yara',sourceLabel:'Fonte integral SharePoint: Orçamento Web.xlsx em 16/10/2026; originais de projetos e PDFs de NF conferidos; evidências SHA-256 no relatório'};
const {book,selected,analyses,fiscalDocs}=await buildFinancialWorkbook(extracted,options);
assert.equal(JSON.stringify(extracted),inputJSON);assert.equal(hash(sourcePath),before);
assert.equal(book.worksheets.length,11);
const numeric=(s,col)=>{let t=0;book.getWorksheet(s).eachRow((r,i)=>{if(i>1&&typeof r.getCell(col).value==='number')t+=r.getCell(col).value;});return Number(t.toFixed(2));};
const rows=(s)=>book.getWorksheet(s).getRows(2,book.getWorksheet(s).rowCount-1)||[];
const details=(s,id,col)=>Number(rows(s).filter(r=>r.getCell(1).value===id).reduce((t,r)=>t+(typeof r.getCell(col).value==='number'?r.getCell(col).value:0),0).toFixed(2));
assert.equal(book.getWorksheet('Resumo Geral').rowCount-1,selected.length);
assert.equal(book.getWorksheet('Conciliação').rowCount-1,selected.length);
assert.equal(new Set(selected.map(q=>q.id)).size,selected.length);
for(const [i,q]of selected.entries()){
const a=analyses.get(q);const r=book.getWorksheet('Resumo Geral').getRow(i+2);const c=book.getWorksheet('Conciliação').getRow(i+2);
assert.equal(r.getCell(19).value,a.revenue);assert.equal(c.getCell(4).value,a.revenue);
for(const [sc,cc] of [[20,7],[21,14],[24,15],[25,16],[26,17],[27,18]])assert.equal(r.getCell(sc).value,c.getCell(cc).value);
if(a.materialCost!=null)assert.ok(Math.abs(details('Materiais Detalhados',q.id,11)-a.materialCost)<0.011);
if(a.serviceCost!=null)assert.ok(Math.abs(details('Serviços e Mão de Obra',q.id,13)-a.serviceCost)<0.011);
if(a.ready)assert.ok(Math.abs([8,11,12,13].reduce((s,k)=>s+(c.getCell(k).value||0),0)-a.serviceCost)<0.011);
if(a.complete)assert.ok(Math.abs(a.revenue-a.estimatedCost-a.estimatedProfit)<0.011);
assert.equal(r.getCell(28).value,null,'Status Pago não deve gerar recebimento');
}
assert.equal(numeric('Resumo Geral',19),numeric('Conciliação',4));
assert.equal(numeric('Resumo Geral',24),numeric('Impostos e Despesas',7));
assert.equal(numeric('Conciliação',19),numeric('Impostos e Despesas',10));
assert.equal(numeric('Resumo Geral',26),numeric('Conciliação',17));
const sourceDocs=[...fiscalDocs.values()];
assert.equal(numeric('Faturamento e Recebimentos',6),Number(sourceDocs.reduce((s,d)=>s+d.amount,0).toFixed(2)));
assert.equal(numeric('Indicadores Mensais',4),numeric('Faturamento e Recebimentos',6));
assert.equal(numeric('Indicadores Mensais',17),sourceDocs.length);
assert.equal(rows('Faturamento e Recebimentos').filter(r=>String(r.getCell(4).value)==='64'&&r.getCell(6).value!=null).length,1);
assert.equal(numeric('Indicadores Mensais',5),0);
const created=selected.filter(q=>sourceDate(q.createdAt)>=options.start&&sourceDate(q.createdAt)<=options.cutoff);
assert.equal(numeric('Indicadores Mensais',13),Number(created.reduce((s,q)=>s+financialAnalysis(q).revenue,0).toFixed(2)));
assert.equal(numeric('Indicadores Mensais',14),created.length);
for(const [col,field]of [[8,'materialCost'],[9,'serviceCost'],[10,'actualTaxCost'],[11,'estimatedProfit']])assert.equal(numeric('Indicadores Mensais',col),Number(created.reduce((s,q)=>s+(financialAnalysis(q)[field]||0),0).toFixed(2)));
for(const r of rows('Impostos e Despesas'))if(r.getCell(3).value==='Acréscimo comercial')assert.equal(r.getCell(7).value,null);
const beforeFile='tmp/Relatorio_Financeiro_Yara_2026.xlsx';
await book.xlsx.writeFile(beforeFile);
const reloaded=new ExcelJS.Workbook();await reloaded.xlsx.readFile(beforeFile);assert.equal(reloaded.worksheets.length,11);
for(const s of reloaded.worksheets){assert.equal(s.views[0].ySplit,1);assert.ok(s.autoFilter);}
assert.equal(XLSX.readFile(beforeFile).SheetNames.length,11);
const missing=selected.filter(q=>!financialAnalysis(q).complete).map(q=>({po:q.poNumber,sale:financialAnalysis(q).revenue,reason:financialAnalysis(q).quality}));
const totals={selected:selected.length,sale:numeric('Resumo Geral',19),knownMaterialCost:numeric('Resumo Geral',20),knownServiceCost:numeric('Resumo Geral',21),estimatedTax:numeric('Resumo Geral',24),knownTotalCost:numeric('Resumo Geral',25),knownResult:numeric('Resumo Geral',26),commercialTax:numeric('Impostos e Despesas',10),invoices:sourceDocs.length,invoiced:numeric('Faturamento e Recebimentos',6),monthlyCreatedSales:numeric('Indicadores Mensais',13),missing,verifiedReceipts:'Não informado',sheets:book.worksheets.map(s=>({name:s.name,dataRows:s.rowCount-1})),checks:'Todos os totais conciliados por PO, abas e datas; arquivo reaberto por ExcelJS e SheetJS; nenhuma fonte alterada'};
fs.writeFileSync('tmp/Relatorio_Financeiro_Yara_2026_validacao.json',JSON.stringify(totals,null,2));
console.log(JSON.stringify(totals,null,2));
